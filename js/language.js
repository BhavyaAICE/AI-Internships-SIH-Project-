// Current language
let currentLanguage = 'en';

// Toggle language function
function toggleLanguage(lang) {
    if (lang === currentLanguage) return;
    
    currentLanguage = lang;
    
    // Update language buttons
    document.getElementById('lang-en').classList.toggle('active', lang === 'en');
    document.getElementById('lang-hi').classList.toggle('active', lang === 'hi');
    
    // Update document language
    document.documentElement.lang = lang;
    
    // Update all translatable elements
    updateTranslations();
    
    // Store language preference
    localStorage.setItem('preferredLanguage', lang);
    
    // Announce language change to screen readers
    announceLanguageChange(lang);
}

// Update all translations
function updateTranslations() {
    const elements = document.querySelectorAll('[id]');
    
    elements.forEach(element => {
        const translationKey = element.id;
        const translation = translations[currentLanguage][translationKey];
        
        if (translation) {
            // Handle different types of elements
            if (element.tagName === 'INPUT' && element.type !== 'submit') {
                if (element.placeholder !== '') {
                    element.placeholder = translation;
                }
            } else if (element.tagName === 'INPUT' && element.type === 'submit') {
                element.value = translation;
            } else if (element.tagName === 'BUTTON') {
                // For buttons with icons, preserve the icon and only update text
                const textNode = Array.from(element.childNodes)
                    .find(node => node.nodeType === Node.TEXT_NODE);
                if (textNode) {
                    textNode.textContent = translation;
                } else {
                    // If no text node, check for span with text
                    const textSpan = element.querySelector('span');
                    if (textSpan) {
                        textSpan.textContent = translation;
                    } else {
                        element.textContent = translation;
                    }
                }
            } else {
                element.textContent = translation;
            }
        }
    });
    
    // Update page title
    const titleTranslations = {
        'index.html': currentLanguage === 'hi' ? 'पीएम इंटर्नशिप सिफारिश पोर्टल - आधिकारिक सरकारी योजनाएं और अवसर' : 'PM Internship Recommendation Portal - Official Government Schemes & Opportunities',
        'auth.html': currentLanguage === 'hi' ? 'साइन इन / पंजीकरण - पीएम इंटर्नशिप सिफारिश पोर्टल' : 'Sign In / Register - PM Internship Recommendation Portal',
        'dashboard.html': currentLanguage === 'hi' ? 'डैशबोर्ड - पीएम इंटर्नशिप सिफारिश पोर्टल' : 'Dashboard - PM Internship Recommendation Portal'
    };
    
    const currentPage = window.location.pathname.split('/').pop() || 'index.html';
    if (titleTranslations[currentPage]) {
        document.title = titleTranslations[currentPage];
    }
}

// Announce language change to screen readers
function announceLanguageChange(lang) {
    const announcement = lang === 'hi' ? 'भाषा हिंदी में बदल गई' : 'Language changed to English';
    
    // Create temporary element for screen reader announcement
    const announcer = document.createElement('div');
    announcer.setAttribute('aria-live', 'polite');
    announcer.setAttribute('aria-atomic', 'true');
    announcer.style.position = 'absolute';
    announcer.style.left = '-10000px';
    announcer.style.width = '1px';
    announcer.style.height = '1px';
    announcer.style.overflow = 'hidden';
    
    document.body.appendChild(announcer);
    announcer.textContent = announcement;
    
    // Remove after announcement
    setTimeout(() => {
        document.body.removeChild(announcer);
    }, 2000);
}

// Initialize language on page load
function initializeLanguage() {
    // Check for saved language preference
    const savedLanguage = localStorage.getItem('preferredLanguage');
    
    // Check for browser language preference
    const browserLanguage = navigator.language || navigator.userLanguage;
    const isHindi = browserLanguage.startsWith('hi');
    
    // Determine initial language
    const initialLanguage = savedLanguage || (isHindi ? 'hi' : 'en');
    
    // Set initial language
    if (initialLanguage !== 'en') {
        toggleLanguage(initialLanguage);
    }
}

// Add keyboard navigation for language toggle
function addLanguageKeyboardSupport() {
    const langButtons = document.querySelectorAll('.lang-btn');
    
    langButtons.forEach(button => {
        button.addEventListener('keydown', (e) => {
            if (e.key === 'Enter' || e.key === ' ') {
                e.preventDefault();
                const lang = button.id.split('-')[1];
                toggleLanguage(lang);
            }
            // Arrow key navigation
            else if (e.key === 'ArrowLeft' || e.key === 'ArrowRight') {
                e.preventDefault();
                const currentIndex = Array.from(langButtons).indexOf(button);
                const nextIndex = e.key === 'ArrowRight' 
                    ? (currentIndex + 1) % langButtons.length
                    : (currentIndex - 1 + langButtons.length) % langButtons.length;
                langButtons[nextIndex].focus();
            }
        });
    });
}

// Initialize when DOM is loaded
document.addEventListener('DOMContentLoaded', () => {
    initializeLanguage();
    addLanguageKeyboardSupport();
});

